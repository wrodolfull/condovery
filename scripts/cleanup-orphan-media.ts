/**
 * Orphan-media cleanup. Dry-run by default; --apply deletes at most 50
 * metadata-backed assets per run, and never touches files lacking metadata.
 *
 * npm run cleanup:orphan-media
 * npm run cleanup:orphan-media -- --apply
 * npm run cleanup:orphan-media -- --apply --days=90 --limit=25
 */
import pg from 'pg';
import {createClient} from '@supabase/supabase-js';
import {findOrphanMediaSQL,lockOrphanMediaSQL,parseOrphanMediaOptions} from '../src/lib/media-orphans';
import {STORAGE_BUCKET} from '../src/lib/supabase';

type Asset={id:string;condominium_id:string;storage_key:string|null;created_at:Date};
let options:ReturnType<typeof parseOrphanMediaOptions>;
try{options=parseOrphanMediaOptions(process.argv.slice(2));}
catch(error){console.error(error instanceof Error?error.message:error);process.exit(2);}

if(!process.env.DATABASE_URL)throw new Error('DATABASE_URL é obrigatória.');
if(options.apply&&(!process.env.SUPABASE_URL||!process.env.SUPABASE_SERVICE_ROLE_KEY))
  throw new Error('SUPABASE_URL e SUPABASE_SERVICE_ROLE_KEY são obrigatórias para --apply.');

const client=new pg.Client({
  connectionString:process.env.DATABASE_URL,
  ssl:process.env.DATABASE_SSL==='true'?{rejectUnauthorized:true}:false
});
const store=options.apply?createClient(
  process.env.SUPABASE_URL!,process.env.SUPABASE_SERVICE_ROLE_KEY!,
  {auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false}}
).storage.from(STORAGE_BUCKET):null;

await client.connect();
let removed=0,skipped=0,failed=0;
try{
  // Review candidate list without modifying metadata or Supabase Storage.
  const candidates=await client.query<Asset>(findOrphanMediaSQL,[options.days,options.limit]);
  console.log(`Orphan media: ${options.apply?'APPLY':'DRY RUN'}; age >= ${options.days} days; limit ${options.limit}; candidates ${candidates.rowCount}.`);
  if(!options.apply){
    for(const asset of candidates.rows)
      console.log(`  Candidate: ${asset.id} | ${asset.storage_key?'Supabase Storage':'legacy database bytes'} | ${new Date(asset.created_at).toISOString()}`);
    console.log('No files deleted. To execute after review, use --apply.');
  }else{
    for(const asset of candidates.rows){
      let transactionOpen=false;
      try{
        await client.query('BEGIN');transactionOpen=true;
        // Re-check age, all reference tables and current ownership under lock
        // immediately before the external deletion.
        const current=await client.query<Asset>(lockOrphanMediaSQL,[asset.id,asset.condominium_id,options.days]);
        const locked=current.rows[0];
        if(!locked||locked.storage_key!==asset.storage_key){
          await client.query('ROLLBACK');transactionOpen=false;skipped++;
          continue;
        }
        if(locked.storage_key){
          // Storage keys are generated by this app below the condominium prefix.
          // An unexpected key is not safe for automatic deletion.
          if(!locked.storage_key.startsWith(locked.condominium_id+'/')
             || !locked.storage_key.endsWith('.webp')){
            console.error(`Skipped unexpected Storage path for ${locked.id}.`);
            await client.query('ROLLBACK');transactionOpen=false;skipped++;
            continue;
          }
          const {error}=await store!.remove([locked.storage_key]);
          if(error)throw new Error('Supabase Storage: '+error.message);
        }
        // Only delete metadata after external Storage removal has succeeded.
        const deleted=await client.query(
          'DELETE FROM public.media_assets WHERE id=$1 AND condominium_id=$2 AND storage_key IS NOT DISTINCT FROM $3 RETURNING id',
          [locked.id,locked.condominium_id,locked.storage_key]
        );
        if(deleted.rowCount!==1)throw new Error('Media metadata changed during cleanup.');
        await client.query('COMMIT');transactionOpen=false;removed++;
        console.log('Deleted unreferenced media: '+locked.id);
      }catch(error){
        if(transactionOpen)await client.query('ROLLBACK');
        failed++;
        console.error('Could not clean media '+asset.id+': '+(error instanceof Error?error.message:String(error)));
      }
    }
    console.log(`Orphan media result: deleted ${removed}; skipped ${skipped}; failures ${failed}.`);
    if(failed)process.exitCode=1;
  }
}finally{
  await client.end();
}
